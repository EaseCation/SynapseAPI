    private static final Object2IntMap<String> NAME_TO_ID = new Object2IntOpenHashMap<>();
    private static final String UNDEFINED = "undefined";

    public static String getName(int id) {
        if (id < 0 || id >= ID_TO_NAME.length) {
            return UNDEFINED;
        }
        String result = ID_TO_NAME[id];
        if (result == null) {
            return UNDEFINED;
        }
        return result;
    }

    public static int getId(String name) {
        return NAME_TO_ID.getOrDefault(name, -1);
    }

    private static void register(int id, String name) {
        ID_TO_NAME[id] = name;
        NAME_TO_ID.put(name, id);
    }

